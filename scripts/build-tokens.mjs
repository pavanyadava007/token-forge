// Builds every token output from one source: CSS variables per theme, a Tailwind v4 theme,
// flat JSON (used by the validator, the diff tool and the migration agent) and typed ES modules.
import StyleDictionary from 'style-dictionary';

const PREFIX = 'tf';
const isPrimitive = (token) => token.filePath.includes('/primitive/');
const isDeprecated = (token) => token.filePath.endsWith('deprecated.json');
const isSemantic = (token) => !isPrimitive(token) && !isDeprecated(token);

// Tailwind v4 reads design tokens from CSS custom properties inside @theme.
// "inline" makes utilities reference our variables, so a theme switch needs no rebuild.
StyleDictionary.registerFormat({
  name: 'tailwind/theme',
  format: ({ dictionary }) => {
    const lines = [];
    for (const token of dictionary.allTokens) {
      const [group, ...rest] = token.path;
      const ref = `var(--${token.name})`;
      if (group === 'color' && isSemantic(token)) lines.push(`  --color-${rest.join('-')}: ${ref};`);
      if (group === 'space') lines.push(`  --spacing-${rest.join('-')}: ${ref};`);
      if (group === 'radius') lines.push(`  --radius-${rest.join('-')}: ${ref};`);
      if (group === 'font' && rest[0] === 'size') lines.push(`  --text-${rest[1]}: ${ref};`);
    }
    return `/* Generated by scripts/build-tokens.mjs. Do not edit. */\n@theme inline {\n${lines.join('\n')}\n}\n`;
  },
});

// Flat name -> resolved value map, plus deprecation info, for tooling.
StyleDictionary.registerFormat({
  name: 'json/tooling',
  format: ({ dictionary }) => {
    const out = {};
    for (const token of dictionary.allTokens) {
      out[token.name] = {
        path: token.path.join('.'),
        value: token.$value ?? token.value,
        type: token.$type ?? token.type,
        tier: isPrimitive(token) ? 'primitive' : isDeprecated(token) ? 'deprecated' : 'semantic',
        ...(token.$deprecated ? { deprecated: token.$deprecated } : {}),
        ...(token.$description ? { description: token.$description } : {}),
      };
    }
    return JSON.stringify(out, null, 2) + '\n';
  },
});

const themes = {
  light: { selector: ":root, [data-theme='light']", filter: () => true },
  dark: { selector: "[data-theme='dark']", filter: (token) => !isPrimitive(token) },
};

for (const [theme, { selector, filter }] of Object.entries(themes)) {
  const sd = new StyleDictionary({
    source: ['tokens/primitive/*.json', `tokens/semantic/${theme}.json`, 'tokens/deprecated.json'],
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: PREFIX,
        buildPath: 'dist/css/',
        files: [
          {
            destination: `${theme}.css`,
            format: 'css/variables',
            filter,
            options: { selector, outputReferences: true },
          },
        ],
      },
      json: {
        transformGroup: 'css',
        prefix: PREFIX,
        buildPath: 'dist/json/',
        files: [{ destination: `${theme}.json`, format: 'json/tooling' }],
      },
      ...(theme === 'light'
        ? {
            tailwind: {
              transformGroup: 'css',
              prefix: PREFIX,
              buildPath: 'dist/tailwind/',
              files: [{ destination: 'theme.css', format: 'tailwind/theme' }],
            },
            js: {
              transformGroup: 'js',
              buildPath: 'dist/js/',
              files: [
                { destination: 'tokens.js', format: 'javascript/es6', filter: isSemantic },
                { destination: 'tokens.d.ts', format: 'typescript/es6-declarations', filter: isSemantic },
              ],
            },
          }
        : {}),
    },
  });
  await sd.buildAllPlatforms();
}

// One entry file that consumers import.
const { writeFile } = await import('node:fs/promises');
await writeFile(
  'dist/css/tokens.css',
  "/* Generated. Light theme on :root, dark theme on [data-theme='dark']. */\n@import './light.css';\n@import './dark.css';\n",
);
console.log('tokens built: dist/css, dist/tailwind, dist/json, dist/js');
